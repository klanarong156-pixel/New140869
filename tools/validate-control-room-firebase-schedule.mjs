import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
const mock = `window.__remote = {}; window.FirebaseAuth = { token: 'test-token', user: { localId: 'uid-test', email: 'test@example.com' } }; window.FirebaseDB = { async get(path) { return window.__remote; }, async put(path, data) { window.__remote = data; return data; }, async delete(path) { delete window.__remote[path]; } };`;
await page.route('**/firebase.js*', route => route.fulfill({ status: 200, contentType: 'application/javascript', body: mock }));
const url = process.env.URL || 'http://127.0.0.1:4185/control-room/';
await page.goto(url, { waitUntil: 'networkidle' });
await page.selectOption('select[name=relay]', 'lightsala');
await page.fill('input[name=onTime]', '19:00');
await page.fill('input[name=offTime]', '22:30');
await page.click('.save-schedule');
await page.waitForTimeout(100);
const result = await page.evaluate(() => ({ remote: window.__remote, status: document.querySelector('[data-firebase-schedule-status]')?.textContent, count: document.querySelector('#scheduleCount')?.textContent }));
if (!(result.remote.relay === 'lightsala' && result.remote.onTime === '19:00')) throw new Error(`Firebase write failed: ${JSON.stringify(result)}`);
if (!result.status.includes('บันทึก Firebase แล้ว')) throw new Error(`Firebase status failed: ${result.status}`);
if (result.count !== '1 รายการ') throw new Error(`UI count failed: ${result.count}`);
console.log(JSON.stringify(result, null, 2));
console.log('PASS Control Room Firebase schedule CRUD write contract');
await browser.close();
